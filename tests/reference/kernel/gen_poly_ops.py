"""Vectors for P1.4 and P1.7 from the kernel's reference: tests/reference/kernel/poly_ops.txt.

poly_reference.py and literal_reference.py in this directory are copies of
the proof kernel's reference scripts. This script draws polynomials with a
fixed seed and records, from those copies, the results of the kernel's
polynomial operations and its byte encodings, so that Mojo tests can compare
without calling Python.

Format, one vector per line (`#` starts a comment):

    add <P> <Q> <R>          R = P + Q
    mul <P> <Q> <R>          R = P * Q
    neg <P> <R>              R = -P
    pow <P> <n> <R>          R = P^n, 0 <= n <= 5
    enc <P> <hex>            the kernel encoding of P (P is neither 0 nor 1)
    bad <hex> <why>          bytes from_kernel_bytes must reject with ENCODING ("-" for no bytes)

A polynomial is `0`, or terms joined by `;` in the kernel's canonical order
(Definition R-3: monomials as lists of (index, exponent) pairs, compared pair
by pair, a proper prefix first, so the constant monomial comes first). A term
is `<coefficient>[<pairs>]`: the coefficient an integer or a reduced fraction
`n/d`, the pairs `index:exponent` joined by `,`, indices strictly increasing
(signed 64-bit), exponents at least 1; `[]` is the constant monomial.
Example: `-1/2[];1[-1:2]` is X_{-1}^2 - 1/2.

Run from the repository root:

    python3 tests/reference/kernel/gen_poly_ops.py > tests/reference/kernel/poly_ops.txt
"""
import random
import struct
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from literal_reference import rational_bytes  # noqa: E402
from poly_reference import add, canonical, decode, encode, mul, neg, power  # noqa: E402

SEED = 20261010
CASES = 60
INDICES = [-(2 ** 63) + 1, -3, -2, -1, 0, 1, 2, 3, 2 ** 62, 2 ** 63 - 1]


def text(poly):
    terms = canonical(poly)
    if not terms:
        return '0'
    out = []
    for monomial, c in terms:
        c = Fraction(c)
        cs = str(c.numerator) if c.denominator == 1 else f'{c.numerator}/{c.denominator}'
        out.append(cs + '[' + ','.join(f'{i}:{e}' for i, e in monomial) + ']')
    return ';'.join(out)


def random_coefficient(rng):
    kind = rng.random()
    if kind < 0.6:
        return Fraction(rng.randint(-9, 9) or 1, rng.choice([1, 1, 1, 2, 3, 7]))
    if kind < 0.9:
        return Fraction(rng.randint(-10 ** 6, 10 ** 6) or 1, rng.randint(1, 10 ** 6))
    return Fraction(rng.choice([-1, 1]) * 2 ** rng.randint(64, 80) + rng.randint(0, 99), rng.choice([1, 3 ** 41]))


def random_poly(rng):
    poly = {}
    for _ in range(rng.randint(0, 4)):
        indices = sorted(rng.sample(INDICES, rng.randint(0, 3)))
        monomial = tuple((i, rng.randint(1, 3)) for i in indices)
        poly[monomial] = poly.get(monomial, Fraction(0)) + random_coefficient(rng)
    return {m: c for m, c in poly.items() if c != 0}


def term(monomial, c):
    """One term in the kernel layout, without checking that it is canonical."""
    data = struct.pack('<I', len(monomial))
    for index, exponent in monomial:
        data += struct.pack('<qI', index, exponent)
    coefficient = rational_bytes(Fraction(c))
    return data + struct.pack('<I', len(coefficient)) + coefficient


def terms(*items):
    return struct.pack('<I', len(items)) + b''.join(term(m, c) for m, c in items)


def main():
    rng = random.Random(SEED)
    print('# Generated by tests/reference/kernel/gen_poly_ops.py; do not edit.')
    encodable = []
    for _ in range(CASES):
        p, q = random_poly(rng), random_poly(rng)
        n = rng.randint(0, 5)
        print(f'add {text(p)} {text(q)} {text(add(p, q))}')
        print(f'mul {text(p)} {text(q)} {text(mul(p, q))}')
        print(f'neg {text(p)} {text(neg(p))}')
        print(f'pow {text(p)} {n} {text(power(p, n))}')
        encodable += [r for r in (p, q, mul(p, q)) if r and r != {(): Fraction(1)}]
    for poly in encodable:
        data = encode(poly)
        assert decode(data) == poly
        print(f'enc {text(poly)} {data.hex()}')
    x0, x1, x2 = ((0, 1),), ((1, 1),), ((2, 1),)
    good = terms((x0, 1), (x1, 1))
    assert decode(good) == {x0: 1, x1: 1}
    bad = [
        (b'', 'empty'),
        (struct.pack('<I', 0), 'no terms'),
        (good + b'\x00', 'trailing byte'),
        (good[:-1], 'truncated'),
        (terms((x1, 1), (x0, 1)), 'terms out of order'),
        (terms((x0, 1), (x0, 2)), 'repeated monomial'),
        (terms((((0, 0),), 2)), 'exponent 0'),
        (terms((((1, 1), (1, 1)), 2)), 'repeated index'),
        (terms((((2, 1), (1, 1)), 2)), 'indices decreasing'),
        (terms((x2, 0)), 'zero coefficient'),
        (terms(((), 1)), 'the constant 1 is ONE, not a literal'),
    ]
    for data, why in bad:
        try:
            decode(data)
        except ValueError:
            print(f'bad {data.hex() or "-"} {why.replace(" ", "_")}')
            continue
        raise AssertionError(f'the reference accepted a bad encoding: {why}')


if __name__ == '__main__':
    main()
